"""Builds the recovery protocol as a report from results/protocol/.

    python3 report/protocol-report.py     # writes report/recovery-protocol.md

Everything in the report comes from protocol.json and the manifests — no
number is written by hand.  The manifests are checked in next to it, so
anyone can verify every line with `md5sum -c`.

The JSON field names and the manifest file names are frozen measurement
ids ('korpusar', 'rabyte', 'manifest_fore_md5', <corpus>-fore.md5, ...);
only the rendered text is English.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
P = ROOT / 'results' / 'protocol'
MIB = 1048576

NAMES = {'kod': 'Source code', 'gif': 'Images (GIF)', 'foto': 'Photos (JPEG)',
         'arkiv': 'Archives (zip/tar.gz)', 'logg': 'Log files',
         'png': 'Images (PNG)', 'film': 'Video', 'silesia': 'Silesia',
         'enwik8': 'enwik8'}


def num(x, d=1):
    return f'{x:,.{d}f}'


def main():
    d = json.loads((P / 'protocol.json').read_text())
    k = d['korpusar']
    all_ok = all(v['identiska'] and v['md5sum_c_ok'] for v in k.values())

    rows = []
    for name, v in k.items():
        rows.append(
            f"| {NAMES.get(name, name)} | {v['filer']:,} | {num(v['rabyte']/MIB)} | "
            f"{num(v['arkivbyte']/MIB)} | `{v['manifest_fore_md5']}` | "
            f"`{v['manifest_efter_md5']}` | "
            f"{'**EQUAL**' if v['identiska'] else '**DIFFERS**'} | "
            f"{'yes' if v['md5sum_c_ok'] else 'NO'} |")

    samples = []
    for name in ('kod', 'foto', 'logg'):
        if name not in k: continue
        samples.append(f"**{NAMES[name]}** — the first three lines of "
                       f"[`{name}-fore.md5`](../results/protocol/{name}-fore.md5):\n\n```")
        samples += k[name]['exempel']
        samples.append('```\n')

    total_files = sum(v['filer'] for v in k.values())
    total_bytes = sum(v['rabyte'] for v in k.values())

    md = f'''# Recovery protocol — hz

**Every file md5-summed before packing and after unpacking, across
{total_files:,} files and {num(total_bytes/MIB/1024, 2)} GiB over {len(k)} corpora.
Outcome: {"all manifests identical, and `md5sum -c` confirms it" if all_ok
else "DEVIATIONS FOUND — see the table"}.**

*{d['datum']} · {d['maskin'].replace('trådar', 'threads')} · {d['nvz']} · mode `small` (the default) ·
the manifests live in [`results/protocol/`](../results/protocol/) and
the protocol is generated by [`tests/protocol.py`](../tests/protocol.py)*

## Method

For each corpus, in this order:

1. **Manifest before:** md5 is computed for every file and written in
   `md5sum` format to `<corpus>-fore.md5`.
2. **Packing** with `hz pack` in the default mode `small`; the archive's
   size and md5 are recorded.
3. **Unpacking** with `hz unpack` into an empty directory.
4. **Manifest after:** the same computation on the unpacked tree, to
   `<corpus>-efter.md5`.
5. **Comparison** line by line — and on top of that, the system's
   `md5sum -c` is run with the *before* manifest against the *unpacked*
   tree, so the check is made by an independent tool and not by the same
   code that wrote the manifests.

The manifest's own md5 (one sum over all file sums) is what the table
shows: if it is equal before and after, every single file is equal, since
one deviating file changes the manifest sum.

## Protocol

| corpus | files | raw MiB | archive MiB | manifest md5 before | manifest md5 after | outcome | `md5sum -c` |
|:--|--:|--:|--:|:--|:--|:-:|:-:|
{chr(10).join(rows)}

## Samples from the manifests

The manifests are ordinary `md5sum` files — here is the start of three of
them, verbatim:

{chr(10).join(samples)}

## Verify it yourself

The whole chain can be re-run on your own machine:

```bash
git clone https://github.com/hugowikstrom/hz && cd hz && make
python3 corpus/build-corpus.py          # or point it at your own directories
python3 tests/protocol.py
```

Or just check an existing manifest against an unpacked tree:

```bash
hz pack my-directory archive.hz
hz unpack archive.hz /tmp/out
cd /tmp/out/my-directory && md5sum -c /path/to/manifest-fore.md5
```

## Notes

- md5 is used here because it is the format people recognize and can run
  with `md5sum -c`.  The packer's own unpack check additionally compares
  blake2b-128 against the archive register for every file, and the broader
  report also verifies permissions, nanosecond timestamps, symlinks and
  directory entries — see [broad-evaluation](broad-evaluation.md),
  section 5.
- The manifest file names keep the suffixes `-fore`/`-efter` (Swedish for
  before/after); they are checked-in artifacts and stay as written.
- The archives in the protocol are temporary; their md5 in `protocol.json`
  exists for traceability, but archive size is not deterministic between
  runs (see broad-evaluation, section 2.2).
'''
    out = ROOT / 'report' / 'recovery-protocol.md'
    out.write_text(md)
    print(f'{out} written ({len(k)} corpora, all ok: {all_ok})')


if __name__ == '__main__':
    main()
